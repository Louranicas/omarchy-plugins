//! Single-device, single-hint ingress for a trusted compositor bridge.
//!
//! Peer identity proves a process, not physical origin. Only a bridge whose owned
//! matched-binding callbacks and census are qualified may produce these frames.
//! No reconnect, auto-release, raw dispatcher or standalone effect authority.
use crate::{Batch, Context, Session};
use desktop_io::ProcessIdentity;
use modal_client::{
    data::ProcessGuard,
    presenter::{Auth, Counter},
};
use modal_runtime::socket::{Connection, ControlSocket};
use serde::{Deserialize, Serialize};
use std::{
    io,
    path::Path,
    time::{Duration, Instant},
};
use vimarchy_core::gestures::Event;

#[derive(Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Frame {
    pub version: u8,
    pub auth: Auth,
    pub bridge_epoch: [u8; 16],
    pub source_revision: Counter,
    pub sequence: Counter,
    /// CLOCK_BOOTTIME milliseconds, same kernel/time namespace as controller.
    pub sent_ms: Counter,
    pub device: Counter,
    pub code: u32,
    pub edge: Edge,
}
#[derive(Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case", deny_unknown_fields)]
pub enum Edge {
    Ready { held: bool },
    Down,
    Up,
    Cancel,
}

pub struct Gate {
    context: Context,
    auth: Auth,
    epoch: [u8; 16],
    device: u64,
    code: u32,
    hint: String,
    sequence: u64,
    ready: bool,
    held: bool,
    press: Option<u64>,
    last_press: u64,
    last_sent: u64,
    // Once per admission; receipt sampling must not move equal source instants.
    clock_anchor: Option<(u64, u64)>,
    poisoned: bool,
}
fn invalid() -> io::Error {
    io::Error::other("input bridge unavailable")
}
impl Gate {
    /// Epoch must be newly generated by the trusted controller for this admission.
    /// Device/code are a previously established census binding, never peer claims.
    pub fn new(
        context: Context,
        auth: Auth,
        epoch: [u8; 16],
        device: u64,
        code: u32,
        hint: String,
    ) -> io::Result<Self> {
        auth.validate().map_err(io::Error::other)?;
        let namespace = format!(
            "omarchy-modal-{}",
            context
                .presenter
                .iter()
                .map(|b| format!("{b:02x}"))
                .collect::<String>()
        );
        if auth.namespace() != namespace
            || auth.fence() != context.fence
            || epoch == [0; 16]
            || device == 0
            || code == 0
            || code > 767
            || hint.len() != 1
            || !vimarchy_core::allocation::ALPHABET
                .contains(hint.chars().next().ok_or_else(invalid)?)
        {
            return Err(invalid());
        }
        Ok(Self {
            context,
            auth,
            epoch,
            device,
            code,
            hint,
            sequence: 0,
            ready: false,
            held: false,
            press: None,
            last_press: 0,
            last_sent: 0,
            clock_anchor: None,
            poisoned: false,
        })
    }
    pub fn invalidate(&mut self, session: &mut Session) {
        self.poisoned = true;
        self.press = None;
        session.invalidate();
    }
    /// Invalid input revokes the session. Caller must dismiss/release through Host;
    /// discarding Err and continuing another ingress is never recovery.
    pub fn route(
        &mut self,
        bytes: &[u8],
        session: &mut Session,
        boot_ms: u64,
        core_ms: u64,
    ) -> io::Result<Option<Batch>> {
        let result = self.route_inner(bytes, session, boot_ms, core_ms);
        if result.is_err() {
            self.invalidate(session);
        }
        result
    }
    fn route_inner(
        &mut self,
        bytes: &[u8],
        session: &mut Session,
        boot_ms: u64,
        core_ms: u64,
    ) -> io::Result<Option<Batch>> {
        if self.poisoned
            || bytes.len() > 2048
            || session.context() != self.context
            || !session.is_valid()
            || core_ms >= session.deadline
            || core_ms < session.last_now
        {
            return Err(invalid());
        }
        let frame: Frame = serde_json::from_slice(bytes)?;
        let sent = frame.sent_ms.get();
        let age = boot_ms
            .checked_sub(sent)
            .filter(|age| *age <= 40)
            .ok_or_else(invalid)?;
        let event_ms = match self.clock_anchor {
            Some((source_origin, core_origin)) => core_origin
                .checked_add(sent.checked_sub(source_origin).ok_or_else(invalid)?)
                .ok_or_else(invalid)?,
            None => core_ms.checked_sub(age).ok_or_else(invalid)?,
        };
        if frame.version != 1
            || frame.auth != self.auth
            || frame.bridge_epoch != self.epoch
            || frame.source_revision.get() != self.context.source_revision
            || frame.sequence.get() != self.sequence.checked_add(1).ok_or_else(invalid)?
            || frame.device.get() != self.device
            || frame.code != self.code
            || sent < self.last_sent
        {
            return Err(invalid());
        }
        self.sequence = frame.sequence.get();
        self.last_sent = sent;
        let event = match frame.edge {
            Edge::Ready { held } if !self.ready && self.sequence == 1 => {
                self.ready = true;
                self.clock_anchor = Some((sent, event_ms));
                self.held = held;
                None
            }
            Edge::Down if self.ready && !self.held => {
                self.held = true;
                self.last_press = self.last_press.checked_add(1).ok_or_else(invalid)?;
                self.press = Some(self.last_press);
                Some(Event::Down {
                    hint: self.hint.clone(),
                    press_id: self.last_press,
                    alt: false,
                    repeat: false,
                })
            }
            Edge::Up if self.ready && self.held => {
                self.held = false;
                self.press.take().map(|press_id| Event::Up { press_id })
            }
            Edge::Cancel => {
                self.poisoned = true;
                self.press = None;
                Some(Event::Cancel)
            }
            _ => return Err(invalid()),
        };
        session
            .input_at(
                self.context,
                event.unwrap_or(Event::Tick),
                event_ms,
                core_ms,
            )
            .map(Some)
            .map_err(|_| invalid())
    }
}
/// Dedicated private endpoint. One pinned compositor connection, never reconnect.
pub struct Ingress {
    socket: ControlSocket,
    peer: ProcessGuard,
    connection: Option<Connection>,
    gate: Gate,
}
impl Ingress {
    pub fn bind(root: &Path, compositor: ProcessIdentity, gate: Gate) -> io::Result<Self> {
        Ok(Self {
            socket: ControlSocket::bind(root)?,
            peer: ProcessGuard::pin(compositor)?,
            connection: None,
            gate,
        })
    }
    /// Live idle returns None without inventing release or advancing the reducer.
    /// The caller still drives Tick and Host continuity checks. Readiness does not
    /// imply a complete frame: partial frames have one bounded absolute deadline.
    pub fn receive(
        &mut self,
        session: &mut Session,
        core_ms: u64,
        deadline: Instant,
    ) -> io::Result<Option<Batch>> {
        let started = Instant::now();
        let result = (|| {
            if self.gate.poisoned
                || !session.is_valid()
                || session.context() != self.gate.context
                || core_ms < session.last_now
                || core_ms >= session.deadline
                || Instant::now() >= deadline
            {
                return Err(invalid());
            }
            self.peer.check()?;
            if self.connection.is_none() {
                let c = match self.socket.accept() {
                    Ok(c) => c,
                    Err(e) if e.kind() == io::ErrorKind::WouldBlock => return Ok(None),
                    Err(e) => return Err(e),
                };
                self.peer.check_peer(c.uid, c.pid)?;
                self.connection = Some(c);
            }
            let c = self.connection.as_mut().ok_or_else(invalid)?;
            self.peer.check_peer(c.uid, c.pid)?;
            if !c.read_ready()? {
                return Ok(None);
            }
            let bytes = c.read_frame(deadline.min(Instant::now() + Duration::from_millis(40)))?;
            self.peer.check_peer(c.uid, c.pid)?;
            self.gate.route(
                &bytes,
                session,
                boottime_ms()?,
                core_ms
                    .checked_add(
                        started
                            .elapsed()
                            .as_millis()
                            .try_into()
                            .map_err(|_| invalid())?,
                    )
                    .ok_or_else(invalid)?,
            )
        })();
        if result.is_err() {
            self.gate.invalidate(session);
            self.connection = None;
        }
        result
    }
}
pub fn boottime_ms() -> io::Result<u64> {
    let mut ts: libc::timespec = unsafe { std::mem::zeroed() };
    if unsafe { libc::clock_gettime(libc::CLOCK_BOOTTIME, &mut ts) } != 0
        || ts.tv_sec < 0
        || !(0..1_000_000_000).contains(&ts.tv_nsec)
    {
        return Err(invalid());
    }
    (ts.tv_sec as u64)
        .checked_mul(1000)
        .and_then(|s| s.checked_add(ts.tv_nsec as u64 / 1_000_000))
        .ok_or_else(invalid)
}

