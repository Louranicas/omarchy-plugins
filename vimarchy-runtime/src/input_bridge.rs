    #[test]
    fn delayed_preheld_repeat_expiry_cancel_and_lost_release_fail_closed() {
        for case in 0..5 {
            let (mut g, mut s) = fixture();
            send(&mut g, &mut s, 1, 2, Edge::Ready { held: case == 0 });
            if case == 0 {
                let f = frame(&g, 2, 3, Edge::Down);
                assert!(g.route(&f, &mut s, 3, 3).is_err());
                continue;
            }
            send(&mut g, &mut s, 2, 3, Edge::Down);
            if case == 1 {
                let f = frame(&g, 3, 4, Edge::Up);
                assert!(g.route(&f, &mut s, 45, 45).is_err());
            }
            if case == 2 {
                let f = frame(&g, 3, 999, Edge::Up);
                assert!(g.route(&f, &mut s, 1001, 1001).is_err());
            }
            if case == 3 {
                let effects = send(&mut g, &mut s, 3, 4, Edge::Cancel);
                assert!(effects.contains(&Effect::Hide));
                let f = frame(&g, 4, 5, Edge::Up);
                assert!(g.route(&f, &mut s, 5, 5).is_err());
            }
            if case == 4 {
                g.invalidate(&mut s);
                let f = frame(&g, 3, 4, Edge::Up);
                assert!(g.route(&f, &mut s, 4, 4).is_err());
            }
            assert!(!s.is_valid());
        }
    }
